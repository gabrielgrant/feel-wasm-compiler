#!/usr/bin/env python3
"""Generate docs/CONFORMANCE-MATRIX.md from the TCK report, the semantic
vectors and the builtin catalog. Usage:
  scripts/conformance-matrix.py reports/tck.json <TCK TestCases dir>
"""
import json, re, sys, glob, os, collections

tck_json, tck_root = sys.argv[1], sys.argv[2]
rep = json.load(open(tck_json))
vectors = json.load(open('tests/vectors/semantic.json'))

# decision/result node -> FEEL texts of that decision (to attribute builtins)
node_texts = {}
for f in glob.glob(os.path.join(tck_root, 'compliance-level-*', '*', '*.dmn')):
    d = os.path.basename(os.path.dirname(f))
    s = open(f, encoding='utf-8').read()
    for m in re.finditer(r'<(?:\w+:)?(?:decision|businessKnowledgeModel)\b[^>]*name="([^"]+)"(.*?)</(?:\w+:)?(?:decision|businessKnowledgeModel)>', s, re.S):
        texts = re.findall(r'<(?:\w+:)?text>(.*?)</(?:\w+:)?text>', m.group(2), re.S)
        node_texts.setdefault((d, m.group(1)), []).append(' '.join(texts))
    # whole-model text for directory-level attribution
    node_texts.setdefault((d, '*'), []).append(' '.join(re.findall(r'<(?:\w+:)?text>(.*?)</(?:\w+:)?text>', s, re.S)))

def unescape(t):
    return t.replace('&lt;', '<').replace('&gt;', '>').replace('&quot;', '"').replace('&amp;', '&')

results = rep['results']
dir_stats = collections.defaultdict(lambda: [0, 0])
for r in results:
    dir_stats[r['dir']][0 if r['status'] == 'pass' else 1] += 1

# --- clause map: clause -> (description, TCK directory patterns, vector clause prefixes)
CLAUSES = [
    ("10.3.1.2", "Grammar rules 1-67 (expressions, precedence, literals)", ["0005", "0008", "0099", "0100", "0075", "0073", "0083", "0093"], ["rule", "grammar", "10.3.1.2"]),
    ("10.3.1.4", "Tokens, multi-word names, white space", ["0034", "0087", "0004"], ["10.3.1.4"]),
    ("10.3.1.5", "Qualified names, path expressions over lists", ["0090", "0040", "0041"], ["10.3.1.5"]),
    ("10.3.1.6", "Name ambiguity resolution (longest match in scope)", ["0034", "0087"], ["10.3.1.6"]),
    ("10.3.2.2", "Equality, identity", ["0068", "0103"], ["Table 52", "Table 53"]),
    ("10.3.2.3.1", "number: decimal128, 34 digits, half-even, range", ["0100", "0099", "1100", "0075", "0077", "0078", "0008"], ["10.3.2.3.1", "10.2.2.2", "Table 57", "Table 59", "Table 60"]),
    ("10.3.2.3.2", "string", ["0002", "0083", "0001"], ["10.3.4.3", "rule 64"]),
    ("10.3.2.3.3", "boolean", ["0106", "0107", "0064", "0065", "0066"], ["Table 50", "Table 51"]),
    ("10.3.2.3.4-8", "time, date, date and time, durations", ["0007", "0093", "1115", "1116", "1117", "1120", "1121", "0074", "0100"], ["10.3.2.3", "Table 72", "Table 66"]),
    ("10.3.2.4", "Ternary logic", ["0106", "0107", "0064", "0065", "0066"], ["Table 50", "Table 51", "Table 49"]),
    ("10.3.2.5", "Lists and filters, list projection", ["0001", "0012", "0039", "0090", "0069", "1151"], ["10.3.2.5", "Table 68"]),
    ("10.3.2.6", "Context, sequential bindings, get value/entries", ["0057", "0040", "0041", "0081", "0080"], ["10.3.2.6", "Table 64"]),
    ("10.3.2.7", "Ranges, endpoint inclusivity", ["1130", "1156", "0071", "0072"], ["10.3.2.7", "Table 39", "Table 55", "Table 67"]),
    ("10.3.2.8 / 10.3.2.13", "Functions: built-in, user-defined (closures), external, positional/named parameters", ["0030", "0031", "0092", "0076", "1131", "0050", "0005"], ["10.3.2.13", "Table 63"]),
    ("10.3.2.9", "Type equivalence, conformance, instance of, implicit conversions", ["0070", "0082", "1157", "0021"], ["10.3.2.9", "Table 61"]),
    ("10.3.2.10", "Decision table semantics (via DMN layer)", ["0004", "0005", "0006", "0007-simple", "0108", "0109", "0110", "0111", "0112", "0113", "0114", "0115", "0116", "0117", "0118", "0119", "0017", "0036", "0037", "0038"], ["10.3.2.10", "rule 14", "rule 15", "rule 8", "rule 9", "rule 13", "rule 7"]),
    ("10.3.2.11", "Scope and context stack", ["0034", "0040", "0041", "0089"], ["10.3.2.11"]),
    ("10.3.2.14", "for loops, partial, ranges of numbers/dates", ["0003", "0033", "0084", "1152"], ["10.3.2.14"]),
    ("rule 46", "Quantified expressions some/every", ["0016", "1153", "1154"], ["rule 46"]),
    ("10.3.2.15", "Semantic mappings (Tables 48-69)", ["0100", "0068", "0072", "0074", "0070"], ["Table"]),
    ("10.3.2.16", "Error handling (null + diagnostics)", ["0082"], ["checker", "validation"]),
    ("10.3.4.11", "now(), today() (clock capability)", ["1148", "1149"], ["10.3.4.11"]),
    ("10.4", "Decision services (DMN integration layer)", ["0085", "1157"], []),
]

def tck_for(prefixes):
    p = f = 0
    dirs = []
    for d, (a, b) in dir_stats.items():
        if any(d.startswith(x) for x in prefixes):
            p += a; f += b; dirs.append(d)
    return p, f, sorted(dirs)

def vec_for(prefixes):
    return [v['id'] for v in vectors if any(v['clause'].startswith(x) for x in prefixes)]

out = []
out.append("# Conformance matrix\n")
out.append("Generated by `scripts/conformance-matrix.py` from `reports/tck.json` (pinned DMN TCK "
           "`5cd912f2`), `tests/vectors/semantic.json` and the builtin catalog. TCK counts are result "
           "nodes evaluated through the generated Wasm backend.\n")
s = rep['summary']
out.append(f"**TCK (compliance levels 2 and 3):** {s['total']} result nodes — {s['pass']} pass, {s['fail']} fail, "
           f"{s['skip']} skip, {s['outOfScope']} out of scope.\n")
out.append(f"**Semantic vectors:** {len(vectors)} cases, each run optimized and unoptimized through native-hosted "
           "generated Wasm (`cargo test -p feel-host --test vectors`) and in Chromium through the in-browser compiler "
           "(`node web/tests/e2e.mjs`).\n")
out.append("\n## Clauses\n")
out.append("| clause | topic | TCK pass / total | TCK directories | vectors |\n|---|---|---:|---|---:|\n")
for c, desc, tprefix, vprefix in CLAUSES:
    p, f, dirs = tck_for(tprefix)
    vs = vec_for(vprefix)
    out.append(f"| {c} | {desc} | {p} / {p+f} | {', '.join(sorted(set(d.split('-')[0] for d in dirs)))} | {len(vs)} |\n")

# --- builtins
sys.path.insert(0, '.')
spec = open('crates/feel-runtime/src/builtins.rs').read()
names = re.findall(r'b!\(\s*"([^"]+)"', spec) + re.findall(r'Builtin \{ name: "([^"]+)"', spec)
out.append("\n## Builtin functions (10.3.4)\n")
out.append("| builtin | TCK result nodes using it (pass/total) | vectors using it |\n|---|---:|---:|\n")
for n in names:
    pat = re.compile(r'(?<![\w ])' + re.escape(n) + r'\s*\(')
    p = t = 0
    for r in results:
        texts = node_texts.get((r['dir'], r['node']), [])
        if any(pat.search(unescape(x)) for x in texts):
            t += 1; p += r['status'] == 'pass'
    vs = sum(1 for v in vectors if pat.search(v['expr']))
    ext = " (extension)" if n == "has key" else ""
    out.append(f"| `{n}`{ext} | {p} / {t} | {vs} |\n")

out.append("\n## TCK directories\n")
out.append("| directory | pass | fail |\n|---|---:|---:|\n")
for d in sorted(dir_stats):
    a, b = dir_stats[d]
    out.append(f"| {d} | {a} | {b} |\n")
open('docs/CONFORMANCE-MATRIX.md', 'w').write(''.join(out))
print("wrote docs/CONFORMANCE-MATRIX.md")
